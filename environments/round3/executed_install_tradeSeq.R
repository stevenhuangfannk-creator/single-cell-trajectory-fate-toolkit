Sys.setenv(PROCESSOR_ARCHITECTURE='AMD64', OMP_NUM_THREADS='1', OPENBLAS_NUM_THREADS='1', MKL_NUM_THREADS='1')
options(timeout=90)
lib <- file.path(getwd(),'work/runtime/R-trajectory/library')
.libPaths(c(lib,.Library))
root <- file.path(getwd(),'outputs/single-cell-trajectory-fate-toolkit')
dir.create(file.path(root,'methods/tradeSeq/logs'),recursive=TRUE,showWarnings=FALSE)
repos <- c(BioCsoft='https://bioconductor.org/packages/3.23/bioc',CRAN='https://cloud.r-project.org')
ap <- available.packages(contriburl=contrib.url(repos,type='win.binary'),type='win.binary')
targets <- c('tradeSeq','BiocParallel')
needed <- unique(c(targets,unlist(tools::package_dependencies(targets,db=ap,which=c('Depends','Imports','LinkingTo'),recursive=TRUE))))
needed <- setdiff(needed,c('R',rownames(installed.packages())))
stopifnot(all(needed %in% rownames(ap)))
m <- data.frame(package=needed,version=ap[needed,'Version'],url=paste0(ap[needed,'Repository'],'/',needed,'_',ap[needed,'Version'],'.zip'),repository_md5=ap[needed,'MD5sum'],bytes=NA_real_,local_md5='',status='PLANNED')
mf <- file.path(root,'environments/round3_tradeSeq_downloads.csv')
write.csv(m,mf,row.names=FALSE)
print(m[,1:2]); flush.console()
dl <- file.path(getwd(),'work/round3/downloads');dir.create(dl,recursive=TRUE,showWarnings=FALSE)
for(i in seq_len(nrow(m))) {
  dest <- file.path(dl,basename(m$url[i]))
  used <- sum(file.info(list.files(file.path(getwd(),'work/round3'),recursive=TRUE,full.names=TRUE))$size,na.rm=TRUE)
  left <- floor(1024^3-used)
  if(left<1e7) stop('Round3 1 GiB guard')
  cat('DOWNLOAD',m$package[i],m$url[i],'\n');flush.console()
  if(!file.exists(dest)) {
    rc <- system2('curl.exe',c('-4','-sS','-L','--retry','2','--fail','--max-time','90','--max-filesize',as.character(left),'--output',shQuote(dest),shQuote(m$url[i])))
    if(rc!=0) stop('Download failed: ',m$package[i])
  }
  m$bytes[i] <- file.info(dest)$size;m$local_md5[i] <- unname(tools::md5sum(dest))
  stopifnot(is.na(m$repository_md5[i]) || m$repository_md5[i]==m$local_md5[i])
  install.packages(dest,repos=NULL,type='win.binary',lib=lib)
  stopifnot(m$package[i] %in% rownames(installed.packages(lib.loc=lib)))
  m$status[i] <- 'INSTALLED';write.csv(m,mf,row.names=FALSE)
}
library(tradeSeq)
cat('INSTALL_OK',as.character(packageVersion('tradeSeq')),'\n')
writeLines(capture.output(sessionInfo()),file.path(root,'environments/round3-tradeSeq-sessionInfo.txt'))
